#requires -Version 7.0

[CmdletBinding()]
param(
  [Parameter(Mandatory = $true)]
  [ValidatePattern('^\d+\.\d+\.\d+$')]
  [string]$Version,

  [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

function Invoke-Checked {
  param(
    [Parameter(Mandatory = $true)][string]$Label,
    [Parameter(Mandatory = $true)][string]$File,
    [string[]]$Arguments = @()
  )

  Write-Host ""
  Write-Host "==> $Label" -ForegroundColor Cyan
  & $File @Arguments
  if ($LASTEXITCODE -ne 0) {
    throw "$Label failed with exit code $LASTEXITCODE"
  }
}

function Get-GitOutput {
  param([string[]]$Arguments)

  $output = & git @Arguments
  if ($LASTEXITCODE -ne 0) {
    throw "git $($Arguments -join ' ') failed with exit code $LASTEXITCODE"
  }
  return @($output)
}

function Format-CommandArg {
  param([string]$Arg)

  if ($Arg -match '[\s"]') {
    return '"' + ($Arg -replace '"', '\"') + '"'
  }
  return $Arg
}

function Get-PreviousReleaseTag {
  param([version]$TargetVersion)

  Invoke-Checked "Fetch tags" "git" @("fetch", "--tags", "origin", "--quiet")
  $tags = Get-GitOutput @("tag", "--list", "v*") | ForEach-Object {
    if ($_ -match '^v(\d+\.\d+\.\d+)$') {
      [pscustomobject]@{
        Tag = $_
        Version = [version]$Matches[1]
      }
    }
  } | Sort-Object Version -Descending

  $previous = $tags | Where-Object { $_.Version -lt $TargetVersion } | Select-Object -First 1
  if (-not $previous) {
    throw "No previous vX.Y.Z tag found before v$TargetVersion"
  }

  return $previous.Tag
}

function Get-ReleaseNoteCategory {
  param([string]$Title)

  if ($Title -match '^(fix|hotfix)(\(|:)' -or $Title -match '(bug|crash|resolve)') {
    return "Fixes"
  }
  if ($Title -match '^(docs|test|chore|refactor)(\(|:)' -or $Title -match '(schema|conformance|progress|pipeline|preprocess|gzip|fixture)') {
    return "Internal"
  }
  return "Features"
}

function Get-MergeItems {
  param([string]$Range)

  $raw = & git log $Range --merges "--format=%H%x1f%s%x1f%b%x1e"
  if ($LASTEXITCODE -ne 0) {
    throw "git log $Range failed with exit code $LASTEXITCODE"
  }

  $text = $raw -join "`n"
  $recordSeparator = [string][char]0x1e
  $fieldSeparator = [string][char]0x1f
  $items = @()

  foreach ($record in ($text -split $recordSeparator)) {
    if (-not $record.Trim()) { continue }
    $fields = $record -split $fieldSeparator, 3
    if ($fields.Count -lt 2) { continue }

    $subject = $fields[1].Trim()
    $body = if ($fields.Count -ge 3) { $fields[2] } else { "" }
    $title = ($body -split "`r?`n" | ForEach-Object { $_.Trim() } | Where-Object { $_ } | Select-Object -First 1)
    if (-not $title) { $title = $subject }

    $prefix = ""
    if ($subject -match '#(\d+)') {
      $prefix = "#$($Matches[1]) "
    }

    $items += [pscustomobject]@{
      Text = "$prefix$title"
      Category = Get-ReleaseNoteCategory $title
    }
  }

  return $items
}

function Write-ReleaseNotesDraft {
  param(
    [string]$PreviousTag,
    [string]$TargetTag,
    [string]$Version
  )

  $range = "$PreviousTag..HEAD"
  $items = Get-MergeItems $range
  $notes = [System.Collections.Generic.List[string]]::new()
  $notes.Add("# LyricLens v$Version")
  $notes.Add("")
  $notes.Add("Draft release notes generated by scripts/release.ps1. Please review and polish before publishing.")
  $notes.Add("")
  $notes.Add("Range: $range")
  $notes.Add("")

  foreach ($category in @("Features", "Fixes", "Internal")) {
    $notes.Add("## $category")
    $bucket = @($items | Where-Object { $_.Category -eq $category })
    if ($bucket.Count -eq 0) {
      $notes.Add("- None.")
    } else {
      foreach ($item in $bucket) {
        $notes.Add("- $($item.Text)")
      }
    }
    $notes.Add("")
  }

  $notesPath = Join-Path ([System.IO.Path]::GetTempPath()) "lyriclens-release-$TargetTag-notes.md"
  [System.IO.File]::WriteAllLines($notesPath, $notes, [System.Text.UTF8Encoding]::new($false))
  return $notesPath
}

if (-not (Get-Command git -ErrorAction SilentlyContinue)) { throw "git is required" }
if (-not (Get-Command npm -ErrorAction SilentlyContinue)) { throw "npm is required" }
if (-not (Get-Command gh -ErrorAction SilentlyContinue)) { throw "gh is required" }

$tag = "v$Version"
$branch = (Get-GitOutput @("branch", "--show-current") | Select-Object -First 1).Trim()
if ($branch -ne "main") {
  if ($DryRun) {
    Write-Warning "Dry run is running on '$branch'. The real release must run from main after the PR is merged."
  } else {
    throw "Release must run from main, current branch is '$branch'"
  }
}

$status = Get-GitOutput @("status", "--porcelain")
if ($status.Count -gt 0) {
  throw "Working tree must be clean before release:`n$($status -join "`n")"
}

$manifestPath = Join-Path $root "manifest.json"
$manifest = Get-Content $manifestPath -Raw | ConvertFrom-Json
if ([string]$manifest.version -ne $Version) {
  throw "manifest.json version is '$($manifest.version)', expected '$Version'"
}

$remoteTag = & git ls-remote --tags origin "refs/tags/$tag"
if ($LASTEXITCODE -eq 0 -and $remoteTag) {
  throw "Remote tag already exists: $tag"
}
if ($LASTEXITCODE -notin @(0, 2)) {
  throw "Could not check remote tag $tag; git ls-remote exited with $LASTEXITCODE"
}

$previousTag = Get-PreviousReleaseTag ([version]$Version)
Write-Host "Release target: $tag"
Write-Host "Previous tag:  $previousTag"

Invoke-Checked "Build plugin" "npm" @("run", "build")
Invoke-Checked "Run tests" "npm" @("test")

$assetPath = Join-Path $root "LyricLens.plugin"
if (-not (Test-Path $assetPath)) {
  throw "Build did not create $assetPath"
}

$hash = (Get-FileHash $assetPath -Algorithm SHA256).Hash.ToLowerInvariant()
$size = (Get-Item $assetPath).Length
Write-Host ""
Write-Host "Asset:  $assetPath"
Write-Host "Bytes:  $size"
Write-Host "SHA256: $hash"

$notesPath = Write-ReleaseNotesDraft -PreviousTag $previousTag -TargetTag $tag -Version $Version
Write-Host "Notes:  $notesPath"

$ghArgs = @(
  "release", "create", $tag,
  "--draft",
  "--title", "LyricLens v$Version",
  "--notes-file", $notesPath,
  $assetPath
)
$displayCommand = "gh " + (($ghArgs | ForEach-Object { Format-CommandArg $_ }) -join " ")

Write-Host ""
if ($DryRun) {
  Write-Host "Dry run: would create draft release with:" -ForegroundColor Yellow
  Write-Host $displayCommand
} else {
  Write-Host "Creating draft release with:" -ForegroundColor Cyan
  Write-Host $displayCommand
  Invoke-Checked "Create draft GitHub release" "gh" $ghArgs
}
